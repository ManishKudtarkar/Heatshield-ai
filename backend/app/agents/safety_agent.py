"""
HeatShield AI — Safety Advisory Agent

Transforms deterministic assessment results into
practical, evidence-conscious safety recommendations.
"""

import json

from strands import Agent
from strands.models import BedrockModel

from app.engine.knowledge_base import format_knowledge_for_agent


# -----------------------------------------------
# CONFIGURATION
# -----------------------------------------------

AWS_REGION = "ap-south-1"
MODEL_ID = "apac.amazon.nova-lite-v1:0"


# -----------------------------------------------
# BEDROCK MODEL
# -----------------------------------------------

model = BedrockModel(
    model_id=MODEL_ID,
    region_name=AWS_REGION,
)


# -----------------------------------------------
# SYSTEM PROMPT
# -----------------------------------------------

SYSTEM_PROMPT = """
You are the Safety Advisory Agent of HeatShield AI.

Your responsibility is to convert validated worker exposure
and environmental assessment data into practical safety advice.

You receive structured assessment results generated by
HeatShield AI's deterministic Python assessment engine.

CORE RULES:

1. Base recommendations on the supplied assessment.
2. Never invent environmental measurements.
3. Never invent worker information.
4. Never generate arbitrary numerical risk scores.
5. Never diagnose medical conditions.
6. Never claim that a worker is completely safe.
7. Never invent universal work-rest schedules.
8. Do not describe apparent temperature as WBGT.
9. Clearly identify missing information.
10. Prioritize practical preventive controls.

RECOMMENDATION PRIORITIES:

- Access to drinking water.
- Access to shade or cooling areas.
- Appropriate workload management.
- Review of protective clothing and equipment.
- Gradual acclimatization for workers who are not acclimatized.
- Collection of missing exposure and break information.
- Appropriate worksite heat monitoring.

WORK-REST GUIDANCE:

Do not prescribe exact work-rest ratios without appropriate
worksite heat measurements, workload classification,
clothing adjustment and applicable occupational guidance.

EMERGENCY RESPONSE:

If the supplied information describes confusion, seizures,
collapse or loss of consciousness during heat exposure,
recommend immediate emergency medical assistance.

Do not delay emergency response for additional assessment.

OUTPUT FORMAT:

1. ASSESSMENT SUMMARY
2. PRIORITY SAFETY ACTIONS
3. WORKER RECOMMENDATIONS
4. SUPERVISOR RECOMMENDATIONS
5. MISSING INFORMATION
6. IMPORTANT LIMITATIONS

Use clear, concise language suitable for workers and supervisors.

Remember:
You provide preventive safety guidance, not medical diagnosis
or a substitute for a qualified occupational safety assessment.
"""


# -----------------------------------------------
# CREATE AGENT
# -----------------------------------------------

safety_agent = Agent(
    model=model,
    system_prompt=SYSTEM_PROMPT,
    callback_handler=None,
)


# -----------------------------------------------
# SUPPORTED LANGUAGES
# -----------------------------------------------

_LANGUAGE_NAMES = {
    "en": "English",
    "hi": "Hindi",
    "gu": "Gujarati",
}


# -----------------------------------------------
# ADVISORY FUNCTION
# -----------------------------------------------

def generate_safety_advisory(
    assessment: dict,
    safety_alerts: dict | None = None,
    language: str = "en",
    response_language: str | None = None,
    knowledge_base: dict | None = None,
) -> str:
    """
    Generate safety guidance from deterministic
    assessment results and proactive safety alerts.

    The ``language`` code is the worker's preferred language and is
    kept alongside the advisory context. ``response_language``
    optionally overrides the display language of the advisory itself
    (for example an English-speaking supervisor reviewing a Hindi
    worker assessment). When omitted, the advisory is written in the
    worker's own language.

    ``knowledge_base`` optionally supplies validated occupational
    heat-safety entries retrieved deterministically from the curated
    HeatShield knowledge base; the advisory must remain consistent
    with them.
    """

    language_name = _LANGUAGE_NAMES.get(language, "English")
    narrative_language_name = (
        _LANGUAGE_NAMES[response_language]
        if response_language in _LANGUAGE_NAMES
        else language_name
    )

    if not assessment.get("success"):
        return "Safety advisory unavailable: assessment failed."

    if assessment.get("assessment_status") == "incomplete":
        status_instruction = """
        IMPORTANT: The assessment is incomplete.
        Do not assign a risk category.
        Clearly explain which information is missing.
        Provide only general preventive recommendations.
        """
    else:
        status_instruction = """
        Explain the assessment status accurately.
        Do not imply that screening results constitute
        a complete occupational heat-risk assessment.
        """

    alerts_instruction = ""
    if safety_alerts and safety_alerts.get("success"):
        alerts_instruction = f"""
        PROACTIVE SAFETY ALERTS (deterministic, authoritative):

        {json.dumps(safety_alerts, indent=2, ensure_ascii=False)}

        Align your advisory with these alerts.
        Do not contradict or override them.
        Reference the most important alerts and their guidance.
        Do not invent additional alert triggers.
        """

    knowledge_instruction = ""
    if knowledge_base and knowledge_base.get("success"):
        knowledge_instruction = f"""
        VALIDATED OCCUPATIONAL SAFETY KNOWLEDGE BASE
        (curated, deterministic grounding context):

        {format_knowledge_for_agent(knowledge_base)}

        Ground your recommendations in these validated entries.
        Do not contradict them and do not present unvalidated
        guidance as established practice. You may adapt wording to
        the worker's situation, but every precaution you recommend
        must be consistent with a listed entry or with the
        assessment data itself.
        """

    prompt = f"""
    Review the following HeatShield AI assessment.

    ASSESSMENT DATA:

    {json.dumps(assessment, indent=2, ensure_ascii=False)}

    {alerts_instruction}

    {knowledge_instruction}

    {status_instruction}

    Generate a practical safety advisory for the worker
    and their construction site supervisor.

    Separate immediate preventive actions from information
    that still needs to be collected.

    Do not invent facts or unsupported measurements.

    LANGUAGE RULES:

    - Respond entirely in {narrative_language_name}.
    - Translate every section heading and sentence into
      {narrative_language_name}; never leave untranslated English text
      inside the advisory.
    - Translate field identifiers (for example
      "continuous_exposure_minutes") into plain, worker-friendly
      {narrative_language_name} wording.
    - Keep only proper nouns, units and measurement values unchanged.
    - The deterministic safety alerts above are localized for a worker
      using {language_name}; your advisory must be written in
      {narrative_language_name}.

    Respond in {narrative_language_name}.
    """

    response = safety_agent(prompt)

    return str(response)


# -----------------------------------------------
# EXECUTION TEST
# -----------------------------------------------

if __name__ == "__main__":

    print("\n" + "=" * 60)
    print("HEATSHIELD AI — SAFETY ADVISORY AGENT")
    print("=" * 60)

    # Import the deterministic assessment pipeline.
    from app.engine.heat_assessment import assess_heat_exposure
    from app.tools.weather_tool import get_weather
    from app.schemas.worker import WorkerProfile

    print("\nRetrieving weather information...")

    weather = get_weather("Vadodara")

    if not weather.get("success"):
        raise RuntimeError(
            f"Weather retrieval failed: {weather.get('error')}"
        )

    worker = WorkerProfile(
        occupation="Construction worker",
        workload="heavy",
        shift_hours=8,
        direct_sunlight=True,
        shade_availability="partial",
        water_access=True,
        acclimatization="not_acclimatized",
        ppe_items=[
            "Safety helmet",
            "Safety boots",
            "Protective clothing",
        ],
        continuous_exposure_minutes=120,
        break_frequency_minutes=None,
        work_area="Outdoor construction site, Vadodara",
    )

    print("Running deterministic assessment...")

    assessment = assess_heat_exposure(
        weather=weather,
        worker=worker.model_dump(),
    )

    if not assessment.get("success"):
        raise RuntimeError(assessment.get("error"))

    print("Generating safety advisory...")

    advisory = generate_safety_advisory(assessment)

    print("\n" + "-" * 60)
    print("HEATSHIELD AI — SAFETY ADVISORY")
    print("-" * 60)

    print(advisory)

    print("\n" + "=" * 60)
    print("SAFETY ADVISORY EXECUTION SUCCESSFUL")
    print("=" * 60)
